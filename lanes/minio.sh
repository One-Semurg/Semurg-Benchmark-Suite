#!/usr/bin/env bash
# OBJECT domain incumbent lane: MinIO (docker:minio/minio). S3 object PUT/GET/STAT/LIST over a
# deterministic small-object set, EQUAL-ANSWER gated byte-for-byte against the SAME reference the
# semurg_object lane uses (identical dataset -> identical GET content hash + STAT size-sum + LIST
# keyset -> identical ANSWER). Driven at MAX CONCURRENCY on this node: MinIO runs single-node
# multi-drive ERASURE CODING across FOUR drives spread over BOTH physical NVMe (2 on the root disk,
# 2 on /data1), and the client fans PUT/GET across all cores ($(nproc) parallel mc streams).
#
# The object set is generated byte-identically to lanes/semurg_object.sh (same OBJ_N / OBJ_SIZE /
# OBJ_SEED defaults, same AES-256-CTR keystream, same obj-%08d.bin key naming), so when the board
# runs semurg_object first (establishing the `object` reference) minio reproduces it exactly ->
# ok-matched. Run standalone, minio ALSO computes its own independent reference from the source
# bytes and gates its measured answer against it, so it only ever emits a number it truly measured.
#
# EQUAL-ANSWER (identical to semurg_object; reproduced from the ACTUAL returned bytes / reported meta):
#   GET   = sha256( join_"\n"( "key<TAB>sha256hex(bytes_returned)" for key in sorted(keys) ) )[:32]
#   STAT  = integer sum of the size MinIO reports for every object (mc ls --json .size)
#   LIST  = sha256( join_"\n"( sorted(keys MinIO enumerates) ) )[:32]
#   ANSWER= sha256( GET "|" STAT "|" LIST )[:32]      -- the single gate value
#
# Emits ONE machine line run_all_domains.sh parses (domain 7, OBJECT), schema-parallel to semurg_object:
#   LANE=minio STATUS=ok LOAD_MS=.. QUERY_MS=.. ANSWER_HASH=<hash> GET_MS=.. STAT_MS=.. LIST_MS=.. OBJECTS=..
# Robust: docker missing/down/noperm, image pull/start failure, engine-not-ready, or a step error ->
# a clean SKIP/FAILED line (never a crash, never a fake number).
set -uo pipefail
here="$(cd "$(dirname "$0")" && pwd)"; . "$here/_common.sh"
export LC_ALL=C
LANE=minio

# ---- 0) docker preflight (same classification + actionable fix as the other docker lanes) --------------
st="$(arena_docker_status)"
[ "$st" = ok ] || { echo "SKIP $LANE reason=docker-$st fix=[$(arena_docker_fix "$st")]"; exit 0; }
command -v openssl   >/dev/null 2>&1 || { echo "SKIP $LANE reason=openssl-missing(needed-for-deterministic-object-content)"; exit 0; }
command -v sha256sum >/dev/null 2>&1 || { echo "SKIP $LANE reason=sha256sum-missing"; exit 0; }

IMG="${MINIO_IMAGE:-minio/minio:RELEASE.2024-01-16T16-07-38Z}"   # a real minio/minio image (mc bundled)
C="arena_minio_$$"

# ---- 1) scratch + erasure drives across BOTH physical disks (fairness: use both its disks) -------------
SC="${ARENA_DATA:-${TMPDIR:-/tmp}/arena_minio}"; mkdir -p "$SC" 2>/dev/null || { echo "SKIP $LANE reason=scratch-unwritable($SC)"; exit 0; }
OBJD="$SC/objsrc"; GETD="$SC/objget"
rm -rf "$OBJD" "$GETD" "$SC/d0" "$SC/d1" 2>/dev/null || true
mkdir -p "$OBJD" "$GETD" "$SC/d0" "$SC/d1" 2>/dev/null || { echo "SKIP $LANE reason=scratch-unwritable($SC)"; exit 0; }
# second disk for drives 3+4 (spreads erasure across both NVMe); fall back to one disk if unavailable.
DISK2_ROOT=""; DISK_NOTE="two-disk-erasure"
for cand in "${MINIO_DISK2:-/data1}" /data0 /mnt/data1; do
  if [ -d "$cand" ] && [ -w "$cand" ]; then DISK2_ROOT="$cand/arena_minio_$$"; break; fi
done
if [ -n "$DISK2_ROOT" ] && mkdir -p "$DISK2_ROOT/d2" "$DISK2_ROOT/d3" 2>/dev/null; then
  D2="$DISK2_ROOT/d2"; D3="$DISK2_ROOT/d3"
else
  mkdir -p "$SC/d2" "$SC/d3" 2>/dev/null; D2="$SC/d2"; D3="$SC/d3"; DISK2_ROOT=""; DISK_NOTE="single-disk-erasure(no-2nd-disk)"
fi
D0="$SC/d0"; D1="$SC/d1"
chmod -R 0777 "$OBJD" "$GETD" "$D0" "$D1" "$D2" "$D3" 2>/dev/null || true  # tolerate any container UID

cleanup(){ docker rm -f "$C" >/dev/null 2>&1 || true; rm -rf "$OBJD" "$GETD" "$D0" "$D1" 2>/dev/null || true
           [ -n "$DISK2_ROOT" ] && rm -rf "$DISK2_ROOT" 2>/dev/null || true; }
trap cleanup EXIT INT TERM
docker rm -f "$C" >/dev/null 2>&1 || true   # reap a stale same-name container

N="${OBJ_N:-4000}"           # object count      (SAME default as semurg_object -> matching dataset)
SIZE="${OBJ_SIZE:-4096}"     # bytes per object  (4 KiB classic small-object S3 workload)
SEED="${OBJ_SEED:-1234567}"  # determinism seed
CYCLES="${OBJ_CYCLES:-3}"    # GET repeats (cold/warm/warm)
P="$(nproc 2>/dev/null || echo 4)"; [ "$P" -gt "$N" ] && P="$N"; [ "$P" -ge 1 ] || P=1

# ---- 2) deterministic object set + INDEPENDENT equal-answer reference (byte-identical to semurg_object)
MAN="$SC/manifest.tsv"; : > "$MAN"; tot=0; i=0
while [ "$i" -lt "$N" ]; do
  key=$(printf 'obj-%08d.bin' "$i"); f="$OBJD/$key"
  head -c "$SIZE" < <(openssl enc -aes-256-ctr -md sha256 -nosalt -pass "pass:${SEED}-${i}" -in /dev/zero 2>/dev/null) > "$f" \
    || { echo "SKIP $LANE reason=object-gen-failed(openssl)"; exit 0; }
  sz=$(stat -c%s "$f" 2>/dev/null || echo 0)
  [ "$sz" = "$SIZE" ] || { echo "SKIP $LANE reason=object-gen-short($key:$sz!=$SIZE)"; exit 0; }
  sha=$(sha256sum "$f" | cut -d' ' -f1)
  printf '%s\t%d\t%s\n' "$key" "$sz" "$sha" >> "$MAN"
  tot=$((tot + sz)); i=$((i + 1))
done
chmod -R a+r "$OBJD" 2>/dev/null || true
sort -k1,1 "$MAN" > "$SC/manifest.sorted.tsv"
awk -F'\t' '{print $1"\t"$3}' "$SC/manifest.sorted.tsv" > "$SC/get.lines"
awk -F'\t' '{print $1}'       "$SC/manifest.sorted.tsv" > "$SC/list.lines"
REF_GET=$(printf '%s' "$(< "$SC/get.lines")"  | sha256sum | cut -c1-32)
REF_LIST=$(printf '%s' "$(< "$SC/list.lines")" | sha256sum | cut -c1-32)
REF_STAT="$tot"
REF_ANSWER=$(printf '%s' "$REF_GET|$REF_STAT|$REF_LIST" | sha256sum | cut -c1-32)
KEYS_SORTED="$SC/list.lines"   # one key per line, sorted (LC_ALL=C)

# ---- 3) start MinIO: single-node 4-drive ERASURE, both disks -----------------------------------------
# throwaway creds for a scratch container -- never echoed (NEVER print tokens).
MINIO_U="arenaminio"; MINIO_P="arenaminiosecret0"
if ! docker run -d --rm --label "$ARENA_LABEL=1" --name "$C" \
      -e MINIO_ROOT_USER="$MINIO_U" -e MINIO_ROOT_PASSWORD="$MINIO_P" \
      -v "$OBJD":/objsrc:ro -v "$GETD":/objget \
      -v "$D0":/d0 -v "$D1":/d1 -v "$D2":/d2 -v "$D3":/d3 \
      "$IMG" server /d0 /d1 /d2 /d3 --address :9000 >/tmp/arena_minio_$$.err 2>&1; then
  echo "SKIP $LANE reason=image-pull-or-start-failed detail=[$(tr -d '\n' </tmp/arena_minio_$$.err | tail -c 90)] fix=[check network/registry, disk space, or: docker pull $IMG]"
  rm -f /tmp/arena_minio_$$.err; exit 0
fi
rm -f /tmp/arena_minio_$$.err
MCH="http://$MINIO_U:$MINIO_P@127.0.0.1:9000"   # mc alias via MC_HOST_arena env; never printed
# no -i: docker exec must NOT attach/consume the orchestrator's plan-pipe stdin (good board citizen)
mc(){ docker exec -e MC_HOST_arena="$MCH" "$C" mc "$@"; }

ready=0
for _ in $(seq 1 60); do
  mc ls arena >/dev/null 2>&1 && { ready=1; break; }
  docker ps -q --no-trunc | grep -q "$(docker inspect -f '{{.Id}}' "$C" 2>/dev/null)" || break   # container died
  sleep 1
done
[ "$ready" = 1 ] || { echo "SKIP $LANE reason=engine-not-ready-in-60s(container crashed or slow; logs: docker logs $C)"; exit 0; }
mc mb --ignore-existing arena/arena >/dev/null 2>&1 || { echo "LANE=$LANE status=FAILED reason=bucket-create-failed(logs: docker logs $C)"; exit 0; }

# split the sorted key list into P slices for the parallel client fan (all cores)
SL="$SC/slices"; rm -rf "$SL"; mkdir -p "$SL"
split -d -n "l/$P" "$KEYS_SORTED" "$SL/ck_" 2>/dev/null || cp "$KEYS_SORTED" "$SL/ck_00"

# one mc process per slice; mode=put (host files -> bucket) | get (bucket -> host dir)
fan_mc(){ # mode
  local mode="$1" ck rc=0 pids=()
  for ck in "$SL"/ck_*; do
    [ -s "$ck" ] || continue
    ( args=(); k=""
      while IFS= read -r k; do [ -n "$k" ] || continue
        if [ "$mode" = put ]; then args+=("/objsrc/$k"); else args+=("arena/arena/$k"); fi
      done < "$ck"
      [ "${#args[@]}" -gt 0 ] || exit 0
      if [ "$mode" = put ]; then mc cp "${args[@]}" arena/arena/ >/dev/null 2>&1
      else mc cp "${args[@]}" /objget/ >/dev/null 2>&1; fi ) &
    pids+=("$!")
  done
  local p; for p in "${pids[@]}"; do wait "$p" || rc=1; done
  return "$rc"
}

# ---- 4) LOAD = parallel PUT of every object ----------------------------------------------------------
t=$(now_ns)
fan_mc put || { echo "LANE=$LANE status=FAILED reason=put-error(engine ran but a PUT slice failed; logs: docker logs $C)"; exit 0; }
LOAD_MS=$(ms_since "$t")

# ---- 5) QUERY = GET (cold/warm/warm), then STAT + LIST from what MinIO reports ------------------------
count_got(){ find "$GETD" -maxdepth 1 -type f -name 'obj-*' 2>/dev/null | wc -l; }
best_get=-1; c=1
while [ "$c" -le "$CYCLES" ]; do
  rm -rf "$GETD"/* 2>/dev/null || true
  t=$(now_ns)
  fan_mc get || { echo "LANE=$LANE status=FAILED reason=get-error(engine ran but a GET slice failed; logs: docker logs $C)"; exit 0; }
  gms=$(ms_since "$t")
  if [ "$c" -ge 2 ] || [ "$CYCLES" -eq 1 ]; then
    [ "$best_get" -lt 0 ] 2>/dev/null && best_get="$gms"; [ "$gms" -lt "$best_get" ] 2>/dev/null && best_get="$gms"
  fi
  c=$((c + 1))
done
[ "$best_get" -ge 0 ] 2>/dev/null || best_get="$gms"
GET_MS="$best_get"
# robustness: GET must be COMPLETE. An incomplete set (transient docker/resource contention, or a
# parallel run wiping shared scratch) is a clean FAILED with a clear reason -- NEVER a misleading
# "answer-mismatch" (which must mean genuinely different bytes on a complete dataset). One retry.
got=$(count_got)
if [ "$got" -ne "$N" ]; then
  rm -rf "$GETD"/* 2>/dev/null || true
  fan_mc get >/dev/null 2>&1 || true
  got=$(count_got)
fi
[ "$got" -eq "$N" ] || { echo "LANE=$LANE status=FAILED reason=get-incomplete(got=$got want=$N; docker/resource-contention or scratch-wiped; logs: docker logs $C)"; exit 0; }

# STAT + LIST from a single mc ls --json (metadata + keyset the engine enumerates)
LSJ="$SC/ls.json"
t=$(now_ns); mc ls --recursive --json arena/arena/ > "$LSJ" 2>/dev/null || { echo "LANE=$LANE status=FAILED reason=list-error(logs: docker logs $C)"; exit 0; }
LIST_MS=$(ms_since "$t"); STAT_MS="$LIST_MS"
# parse per-line JSON objects: extract "key":"..." and "size":N (no jq dependency)
sed -n 's/.*"key":"\([^"]*\)".*/\1/p' "$LSJ" | sort > "$SC/prod.keys"
pk=$(wc -l < "$SC/prod.keys" 2>/dev/null || echo 0)
if [ "$pk" -ne "$N" ]; then                     # retry the enumeration once on an incomplete listing
  mc ls --recursive --json arena/arena/ > "$LSJ" 2>/dev/null || true
  sed -n 's/.*"key":"\([^"]*\)".*/\1/p' "$LSJ" | sort > "$SC/prod.keys"
  pk=$(wc -l < "$SC/prod.keys" 2>/dev/null || echo 0)
fi
[ "$pk" -eq "$N" ] || { echo "LANE=$LANE status=FAILED reason=list-incomplete(listed=$pk want=$N; contention or scratch-wiped; logs: docker logs $C)"; exit 0; }
PROD_STAT=$(sed -n 's/.*"size":\([0-9]\{1,\}\).*/\1/p' "$LSJ" | awk '{s+=$1} END{print s+0}')
PROD_LIST=$(printf '%s' "$(< "$SC/prod.keys")" | sha256sum | cut -c1-32)

# GET content hash from the ACTUAL returned bytes (last warm download still on disk in $GETD)
: > "$SC/prod.get.lines"
while IFS= read -r k; do
  gf="$GETD/$k"
  if [ -f "$gf" ]; then gsha=$(sha256sum "$gf" | cut -d' ' -f1); else gsha="MISSING"; fi
  printf '%s\t%s\n' "$k" "$gsha" >> "$SC/prod.get.lines"
done < "$KEYS_SORTED"
PROD_GET=$(printf '%s' "$(< "$SC/prod.get.lines")" | sha256sum | cut -c1-32)
PROD_ANSWER=$(printf '%s' "$PROD_GET|$PROD_STAT|$PROD_LIST" | sha256sum | cut -c1-32)

# ---- 6) EQUAL-ANSWER GATE: emit ok ONLY if MinIO reproduced the independent reference -----------------
if [ "$PROD_ANSWER" != "$REF_ANSWER" ]; then
  echo "LANE=$LANE STATUS=dnf REASON=answer-mismatch(prod=$PROD_ANSWER ref=$REF_ANSWER get=$PROD_GET/$REF_GET stat=$PROD_STAT/$REF_STAT list=$PROD_LIST/$REF_LIST)"
  exit 0
fi
echo "LANE=$LANE STATUS=ok LOAD_MS=${LOAD_MS} QUERY_MS=${GET_MS} ANSWER_HASH=${PROD_ANSWER} GET_MS=${GET_MS} STAT_MS=${STAT_MS} LIST_MS=${LIST_MS} OBJECTS=${N}"
